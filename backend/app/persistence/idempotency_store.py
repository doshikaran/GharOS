"""`FirestoreIdempotencyStore` — real, durable backing for
`contracts.actions.IdempotencyKey` / `contracts.repositories.IdempotencyStore`
(spec §19.1).

Keys are generated by `IdempotencyKey.as_str()` from
`(entity_id, action_type, cycle)`. Payments are the strictest case — one
debit per due-ID per cycle — enforced at the *tool* level (E3), not here;
this store only guarantees that a given key can reserve, record, and be
replayed exactly once without a duplicate effect, durably across process
restarts (backed by Firestore, not process memory).
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from google.cloud import firestore

_IDEMPOTENCY_COLLECTION = "idempotency_keys"

_STATUS_RESERVED = "reserved"
_STATUS_COMPLETED = "completed"


class FirestoreIdempotencyStore:
    """Structurally satisfies `contracts.repositories.IdempotencyStore`.

    Each key is one Firestore document, keyed by the idempotency key
    string itself. `check_and_reserve` atomically reads-or-creates that
    document inside a transaction, so two concurrent callers (or a caller
    replaying after a crash) racing on the same key can never both observe
    "first use". A reservation with no recorded result yet is *not* treated
    as "already used" — matching the protocol's documented "first use"
    semantics (`record_result` is what completes a reservation).
    """

    def __init__(self, client: firestore.Client) -> None:
        self._client = client

    def check_and_reserve(self, key: str) -> str | None:
        """Returns the prior result reference if `key` already completed,
        or `None` (having durably reserved the key) if this is the first
        use, or if the key is reserved-but-not-yet-completed (e.g. the
        process that reserved it crashed before calling `record_result` —
        the caller is expected to proceed and call `record_result` itself,
        matching the two-step protocol this class implements)."""
        doc_ref = self._client.collection(_IDEMPOTENCY_COLLECTION).document(key)
        transaction = self._client.transaction()

        @firestore.transactional
        def _run(txn: firestore.Transaction) -> str | None:
            snapshot = doc_ref.get(transaction=txn)
            if snapshot.exists:
                data = snapshot.to_dict() or {}
                if data.get("status") == _STATUS_COMPLETED:
                    result_ref = data.get("result_ref")
                    return str(result_ref) if result_ref is not None else None
                return None
            txn.set(
                doc_ref,
                {
                    "key": key,
                    "status": _STATUS_RESERVED,
                    "result_ref": None,
                    "reserved_at": datetime.now(UTC),
                },
            )
            return None

        result: str | None = _run(transaction)
        return result

    def record_result(self, key: str, result_ref: str) -> None:
        """Durably records the completed effect's result reference. Never
        overwrites an already-completed key with a different result —
        replaying `record_result` with the same `result_ref` is a
        harmless no-op; a different `result_ref` for an already-completed
        key is a caller bug (raises `ValueError`, since
        `contracts.errors.IdempotencyConflict` is reserved for the tool
        layer's replay-detection path per its own docstring, not for this
        low-level store)."""
        doc_ref = self._client.collection(_IDEMPOTENCY_COLLECTION).document(key)
        transaction = self._client.transaction()

        @firestore.transactional
        def _run(txn: firestore.Transaction) -> None:
            snapshot = doc_ref.get(transaction=txn)
            existing: dict[str, Any] = {}
            if snapshot.exists:
                existing = snapshot.to_dict() or {}
            if existing.get("status") == _STATUS_COMPLETED:
                if existing.get("result_ref") != result_ref:
                    raise ValueError(
                        f"idempotency key '{key}' already completed with a different result "
                        f"({existing.get('result_ref')!r} != {result_ref!r})"
                    )
                return
            txn.set(
                doc_ref,
                {
                    "key": key,
                    "status": _STATUS_COMPLETED,
                    "result_ref": result_ref,
                    "reserved_at": existing.get("reserved_at", datetime.now(UTC)),
                    "completed_at": datetime.now(UTC),
                },
            )

        _run(transaction)
