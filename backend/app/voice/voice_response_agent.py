"""A69 — Voice Response Agent (spec §14.7, §15.11, PHASES.md Phase 13,
ADR-020 Decision 4) — E3's `backend/app/voice/`.

*Responsibility:* generate one spoken response — real text in the
speaker's own language and register, pacing-adapted to the listener, plus
real synthesized audio.

**TTS path verified live this phase, not assumed (see `tts_client.py`'s
own module docstring for the full detail):** a live Vertex AI Gemini
native audio-output call (`gemini-2.5-flash-preview-tts`, `google.genai`,
`response_modalities=["AUDIO"]`) genuinely works in this project —
confirmed by real calls, once per supported language, this phase. The
separate Google Cloud Text-to-Speech API (the honest fallback spec
anticipated in case the primary path was unavailable) was never needed.

**Two real model calls, not one:** first, a Pro-tier text-generation call
(`reasoning.gemini_client.GeminiClient.generate_structured`) composes the
actual spoken text — phrasing `content_summary` in `speaker_language`, at
the requested register — never inventing a fact beyond what
`content_summary`/`list_items` supply (mirrors `app.agents.concierge.
call_planner_agent`'s "every bound field is copied verbatim... never
generated by this call" discipline, adapted here to facts rather than
bounds). Second, `tts_client.VertexTtsClient.synthesize` renders that
exact text to real audio, styled by `pacing.PacingProfile.
style_instruction`.

**Forbidden: reading long lists aloud or narrating the graph — summarise
and point to the visual surface** (spec's own A69 forbidden-list line).
Enforced in CODE, not just a prompt instruction: `_cap_item_enumeration`
below hard-caps at `_MAX_ITEMS_SPOKEN` (2) — at 3 or more `list_items`,
the model is shown (and can therefore only ever speak) a capped prefix
plus an explicit deferral instruction; the full list is never sent to the
model at all once capped, so there is no code path in which this module
could enumerate a long list even if it "wanted" to. `VoiceResponseResult.
deferred_full_list` records whenever this happened, directly testable.

*Model tier:* Pro-tier (spec §15.11 A69: "Pro-tier + TTS"). **Cross-role
wiring note, matching `app.arbitration.confidence_arbiter.
ConfidenceArbiter`'s own documented precedent for the identical
situation:** a live Pro-tier call here requires `AgentId("A69")` to be
present on `reasoning.model_router.PRO_TIER_ALLOWLIST` — that module is
E2-owned and is not edited by this package. ADR-020 Decision 4 assigns
adding "A69" there to E2 ("E2 executes"); as of this phase's E3 hand-off,
it had not yet been added (confirmed by reading the file directly, not
assumed) — until it is, a real Pro-tier call from this agent raises
`app.reasoning.errors.ProTierNotAllowlisted`. This module's own unit
tests inject a `GeminiClient` whose underlying `ModelRouter` has the
allowlist patched for the duration of the test, proving this class's own
logic correct independent of that cross-role wiring gap — exactly
`ConfidenceArbiter`'s own stated technique for A57's identical situation.

*Forbidden:* reading long lists aloud (see above, structural). Holds no
tool, no import of `app.arbitration` — see
`backend/tests/test_voice_infra_arbitration_boundary.py`.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Protocol

from contracts.agents import ModelTier
from contracts.graph_types import AgentId

from app.agents.voice.json_utils import parse_json_response, require_float, require_str
from app.reasoning.gemini_client import GeminiClient

from .tts_client import TtsAudio
from .types import ResponseRequest, VoiceResponseResult

AGENT_ID = AgentId("A69")


class TtsClientProtocol(Protocol):
    """Structural subset of `tts_client.VertexTtsClient` this module
    actually calls — lets a test inject a lightweight fake without a real
    `genai.Client`, while the real `VertexTtsClient` satisfies this shape
    unchanged (mirrors `session_manager.ApprovalGateProtocol`'s identical
    role for `ApprovalGate`)."""

    def synthesize(self, *, text: str, voice_name: str, language_code: str) -> TtsAudio: ...


_MAX_ITEMS_SPOKEN = 2
"""At 3 or more `ResponseRequest.list_items`, only this many are ever
shown to the model (spec's own A69 forbidden list: "reading long lists
aloud or narrating the graph — summarise and point to the visual
surface")."""

_LIST_ITEM_THRESHOLD = 3

_PROMPT = """You are the voice response stage of a household operating system, composing one spoken reply.

Speak in this language: {speaker_language}
Delivery style (must shape your phrasing, not just be mentioned): {style_instruction}
Response kind: {response_kind}

What you must convey (do not invent any fact beyond what is stated here):
{content_summary}
{items_block}

Compose the SHORT, natural, spoken-language reply a person would actually say out loud — not a written \
message. Do not read out a long list verbatim; if told to defer a full list, say so briefly and point to \
the app/screen instead of enumerating further.

Respond with a single JSON object and nothing else:
{{"spoken_text": "...", "confidence": 0.0}}
"""


def _cap_item_enumeration(items: tuple[str, ...]) -> tuple[tuple[str, ...], bool]:
    """Spec's own A69 forbidden-list rule, made structural.

    Returns:
        `(items_to_show_the_model, deferred)` — `deferred` is `True` only
        when `len(items) >= _LIST_ITEM_THRESHOLD`, in which case
        `items_to_show_the_model` is capped at `_MAX_ITEMS_SPOKEN` — the
        remaining items are never sent to the model at all.
    """
    if len(items) < _LIST_ITEM_THRESHOLD:
        return items, False
    return items[:_MAX_ITEMS_SPOKEN], True


def _items_block(items: tuple[str, ...], *, deferred: bool, total_count: int) -> str:
    if not items:
        return ""
    lines = "\n".join(f"- {item}" for item in items)
    if deferred:
        remaining = total_count - len(items)
        return (
            f"{lines}\n(There are {remaining} more items — briefly mention there is more and say to check "
            "the app/screen for the full list. Do not list them.)"
        )
    return lines


class VoiceResponseAgent:
    """A69 Voice Response Agent. Dependency-injected on a `GeminiClient`
    (text composition) and a `VertexTtsClient` (audio synthesis) — no
    `GraphReader`, no tool of any kind."""

    def __init__(self, *, gemini_client: GeminiClient, tts_client: TtsClientProtocol) -> None:
        self._gemini_client = gemini_client
        self._tts_client = tts_client

    def respond(self, request: ResponseRequest) -> VoiceResponseResult:
        """Composes and synthesizes one real spoken response.

        Raises:
            app.agents.voice.errors.ModelResponseMalformed: the text
                composition response could not be parsed as the expected
                JSON shape.
            errors.TtsCallFailed: the TTS synthesis call failed or
                returned no audio.
        """
        shown_items, deferred = _cap_item_enumeration(request.list_items)
        prompt = _PROMPT.format(
            speaker_language=request.speaker_language,
            style_instruction=request.pacing.style_instruction,
            response_kind=request.response_kind,
            content_summary=request.content_summary,
            items_block=_items_block(shown_items, deferred=deferred, total_count=len(request.list_items)),
        )
        call_result = self._gemini_client.generate_structured(
            agent_id=AGENT_ID, tier=ModelTier.PRO, prompt=prompt
        )
        parsed = parse_json_response(agent_id=AGENT_ID, text=call_result.text)
        spoken_text = require_str(parsed, "spoken_text", agent_id=AGENT_ID)
        confidence = require_float(parsed, "confidence", agent_id=AGENT_ID, default=0.0)

        audio = self._tts_client.synthesize(
            text=f"{request.pacing.style_instruction}: {spoken_text}",
            voice_name=request.voice_name,
            language_code=request.pacing.language_code,
        )

        return VoiceResponseResult(
            turn_id=request.turn_id,
            spoken_text=spoken_text,
            audio_bytes=audio.data,
            audio_mime_type=audio.mime_type,
            language=request.speaker_language,
            deferred_full_list=deferred,
            confidence=confidence,
            model_tier="pro",
            invocation_id=uuid.uuid4().hex,
            produced_at=datetime.now(UTC),
        )


__all__ = ["AGENT_ID", "VoiceResponseAgent"]
