#!/usr/bin/env bash
# GharOS — scripts/capture_deploy_proof.sh
#
# Read-only deployment-proof capture helper (PHASES.md Phase 15 / spec
# §6.3). Runs the `gcloud` queries that back `docs/DEPLOYMENT_PROOF.md`
# and writes ONE timestamped Markdown block to stdout, ready to paste
# into that file's "Requirement 4 / overnight run" section.
#
# STRICTLY READ-ONLY. This script only calls:
#   gcloud ... describe / list / logging read
# It NEVER deploys, updates, creates, deletes, pauses, or triggers
# anything. Safe to run at any time, including mid-demo. It does not
# touch --min-instances / --max-instances (that is infra/deploy_*.sh and
# infra/teardown.sh); running this does not change project state or cost.
#
# Usage:
#   ./scripts/capture_deploy_proof.sh                 # last 24h of logs
#   ./scripts/capture_deploy_proof.sh --since 20h     # custom log freshness
#   ./scripts/capture_deploy_proof.sh > /tmp/proof-block.md
#
# Requires: gcloud CLI on PATH, an active auth session, and read access to
# the GharOS project (resolved exactly as infra/ scripts resolve it).

set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."   # repo root
source ./infra/_common.sh

FRESHNESS="24h"
if [[ "${1:-}" == "--since" && -n "${2:-}" ]]; then
  FRESHNESS="$2"
fi

# `gcloud logging read --freshness` is SILENTLY IGNORED when combined with
# `--order=asc` (a real, confirmed gcloud quirk — freshness only applies
# with the default `--order=desc`). This capture wants oldest-first
# firings, so it computes an absolute UTC cutoff from $FRESHNESS and puts
# an explicit `timestamp>=` in the log filter instead of trusting
# `--freshness`. Supports `<N>h` and `<N>d`.
freshness_cutoff_utc() {
  local spec="$1" num unit
  num="${spec%[hdHD]}"
  unit="${spec: -1}"
  [[ "$num" =~ ^[0-9]+$ ]] || die "--since must look like 24h or 2d (got: $spec)"
  local hours="$num"
  case "$unit" in
    d | D) hours=$((num * 24)) ;;
    h | H) hours="$num" ;;
    *) die "--since must end in h or d (got: $spec)" ;;
  esac
  # BSD/macOS date first, then GNU date.
  date -u -v-"${hours}"H +%Y-%m-%dT%H:%M:%SZ 2>/dev/null \
    || date -u -d "${hours} hours ago" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null \
    || die "could not compute a cutoff timestamp with this platform's 'date'"
}

require_gcloud
require_auth

project_id="$(resolve_project_id || true)"
[[ -n "$project_id" ]] || die "No GharOS project found (set GHAROS_PROJECT_ID or run ./infra/setup_gcp.sh)."

now_utc="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
since_utc="$(freshness_cutoff_utc "$FRESHNESS")"

# All output below is Markdown on stdout. Progress/log noise goes to stderr
# (via log()/warn()) so `... > block.md` produces a clean paste.
log "Project: $project_id  Region: $GHAROS_REGION  (read-only capture, freshness=$FRESHNESS)"

emit() { printf '%s\n' "$*"; }
# Run a read-only gcloud query. The human-readable form of each command is
# already emitted to stdout just above its call site (the `$ gcloud ...`
# lines), so this wrapper stays silent on stderr and just executes.
run() { "$@"; }

emit "### Deployment-proof capture — ${now_utc} (read-only)"
emit ""
emit "Generated by \`scripts/capture_deploy_proof.sh\` against project \`${project_id}\`, region \`${GHAROS_REGION}\`."
emit "Every command below is a \`describe\` / \`list\` / \`logging read\` — no mutation, no deploy, no cost."
emit ""

emit '```'
emit "\$ gcloud run services list --project=${project_id} --region=${GHAROS_REGION}"
run gcloud run services list --project="$project_id" --region="$GHAROS_REGION" \
  --format='table(metadata.name,status.url,status.latestReadyRevisionName,status.traffic[0].percent)' 2>&1 || true
emit '```'
emit ""

for svc in "$GHAROS_API_SERVICE" "$GHAROS_WEB_SERVICE"; do
  emit "**${svc} — scaling annotations (min-instances proof) + latest revision:**"
  emit '```'
  emit "\$ gcloud run services describe ${svc} --project=${project_id} --region=${GHAROS_REGION} \\"
  emit "    --format=\"yaml(status.latestReadyRevisionName,spec.template.metadata.annotations)\""
  run gcloud run services describe "$svc" --project="$project_id" --region="$GHAROS_REGION" \
    --format='yaml(status.latestReadyRevisionName,spec.template.metadata.annotations)' 2>&1 || true
  emit '```'
  emit "_A \`minScale\` / \`autoscaling.knative.dev/minScale\` line absent above == min-instances=0 (Cloud Run only emits it when set > 0)._"
  emit ""

  emit "**${svc} — recent revisions (source-build proof: \`build-source-location\` == buildpack zip upload, no Dockerfile):**"
  emit '```'
  emit "\$ gcloud run revisions list --service=${svc} --project=${project_id} --region=${GHAROS_REGION} --limit=5"
  run gcloud run revisions list --service="$svc" --project="$project_id" --region="$GHAROS_REGION" \
    --limit=5 --format='table(metadata.name,status.conditions[0].status,metadata.creationTimestamp)' 2>&1 || true
  latest_rev="$(gcloud run services describe "$svc" --project="$project_id" --region="$GHAROS_REGION" \
    --format='value(status.latestReadyRevisionName)' 2>/dev/null || true)"
  if [[ -n "$latest_rev" ]]; then
    emit ""
    emit "\$ gcloud run revisions describe ${latest_rev} --project=${project_id} --region=${GHAROS_REGION} \\"
    emit "    --format=\"value(metadata.annotations['run.googleapis.com/build-source-location'])\""
    run gcloud run revisions describe "$latest_rev" --project="$project_id" --region="$GHAROS_REGION" \
      --format="value(metadata.annotations['run.googleapis.com/build-source-location'])" 2>&1 || true
  fi
  emit '```'
  emit ""
done

emit "**Cloud Scheduler jobs (state + last real attempt):**"
emit '```'
emit "\$ gcloud scheduler jobs list --project=${project_id} --location=${GHAROS_REGION}"
run gcloud scheduler jobs list --project="$project_id" --location="$GHAROS_REGION" \
  --format='table(name.basename(),schedule,timeZone,state,lastAttemptTime)' 2>&1 || true
emit '```'
emit ""

emit "**Pub/Sub topics + push subscriptions:**"
emit '```'
emit "\$ gcloud pubsub topics list --project=${project_id}"
run gcloud pubsub topics list --project="$project_id" --format='value(name.basename())' 2>&1 || true
emit ""
emit "\$ gcloud pubsub subscriptions list --project=${project_id}"
run gcloud pubsub subscriptions list --project="$project_id" \
  --format='value(name.basename(),pushConfig.pushEndpoint)' 2>&1 || true
emit '```'
emit ""

emit "**Scheduler -> Pub/Sub -> Cloud Run firings since ${since_utc} (genuine unattended run):**"
emit ""
emit "Non-heartbeat scheduled ticks (nightly consolidation + follow-up sweep) — every one, oldest first:"
emit '```'
sched_filter='resource.type=cloud_run_revision AND resource.labels.service_name='"$GHAROS_API_SERVICE"' AND (textPayload:"consolidation_nightly_tick_received" OR textPayload:"followup_sweep_tick_received" OR textPayload:"consolidation_nightly_completed") AND timestamp>="'"$since_utc"'"'
emit "\$ gcloud logging read '<consolidation+followup filter> AND timestamp>=\"${since_utc}\"' --project=${project_id} --order=asc"
run gcloud logging read "$sched_filter" --project="$project_id" \
  --order=asc --format='value(timestamp,textPayload)' 2>&1 | head -60 || true
emit '```'
emit ""
emit "Heartbeat ticks — first, last, and total count in the window:"
emit '```'
hb_filter='resource.type=cloud_run_revision AND resource.labels.service_name='"$GHAROS_API_SERVICE"' AND textPayload:"heartbeat_received" AND timestamp>="'"$since_utc"'"'
hb_timestamps="$(gcloud logging read "$hb_filter" --project="$project_id" --order=asc \
  --format='value(timestamp)' --limit=100000 2>/dev/null || true)"
hb_count="$(printf '%s\n' "$hb_timestamps" | grep -c . || true)"
emit "first: $(printf '%s\n' "$hb_timestamps" | head -1)"
emit "last:  $(printf '%s\n' "$hb_timestamps" | tail -1)"
emit "count: ${hb_count:-0}"
emit '```'
emit "_Expected ~12 heartbeat firings/hour on the \`*/5 * * * *\` cron; a materially lower count means missed ticks (report it honestly, do not round up)._"
emit ""
emit "_Captured ${now_utc} by \`scripts/capture_deploy_proof.sh\` — read-only. Run \`./infra/teardown.sh\` after the final capture to hold Cloud Run at min-instances=0._"

warn "Done. Redirect stdout to a file and paste the block into docs/DEPLOYMENT_PROOF.md."
